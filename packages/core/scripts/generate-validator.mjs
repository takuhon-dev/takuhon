/**
 * Generate a standalone (precompiled) Ajv validator for the takuhon schema.
 *
 * Ajv normally compiles a schema into a validator at runtime via `new
 * Function`, which a strict Content-Security-Policy without `'unsafe-eval'`
 * blocks in the browser (the admin SPA runs under exactly such a policy,
 * security.md §1.2). This script emits the validator as plain JavaScript ahead
 * of time so `validate()` carries no runtime code generation and runs anywhere,
 * including eval-restricted runtimes.
 *
 * Run via `pnpm --filter @takuhon/core generate` (also wired into `prebuild`).
 * The output is committed so the package builds without re-running Ajv.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, '../takuhon.schema.json');
const outPath = resolve(here, '../src/generated/takuhon-validator.cjs');

const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));

// Match the runtime options the previous in-process compile used so behaviour
// is identical. CommonJS output (no `esm`) is deliberate: the standalone code
// references ajv-formats' formats and a couple of ajv runtime helpers via
// `require(...)`. Emitting CommonJS keeps those as genuine CJS requires that
// bundlers (tsup/esbuild for the dist, Vite for tests) resolve and inline with
// correct interop — an ESM build leaves `require()` as an unresolved runtime
// global. The bundled output therefore carries no runtime require/eval and
// runs under a strict CSP.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true },
});
addFormats(ajv);

const validate = ajv.compile(schema);
const moduleCode = standaloneCode(ajv, validate);

mkdirSync(dirname(outPath), { recursive: true });
const banner =
  '/* eslint-disable */\n' +
  '// AUTO-GENERATED by scripts/generate-validator.mjs — do not edit by hand.\n' +
  '// Standalone Ajv validator for takuhon.schema.json (no runtime eval).\n';
writeFileSync(outPath, banner + moduleCode, 'utf8');

console.log(`Wrote ${outPath} (${moduleCode.length} bytes)`);
