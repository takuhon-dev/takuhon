// Postbuild: inline the built browser-widget assets as string exports.
//
// `vite build` produces `dist/contact-widget.{js,css}` as static files. Host
// adapters that have no asset-hosting layer (e.g. `@takuhon/cloudflare`, which
// bundles everything into one Worker) need the *content* of those files, not a
// path, so they can serve them from a route. This script reads the two built
// files and writes `dist/assets.js` (+ `dist/assets.d.ts`) exporting their text,
// surfaced to consumers via the package's `./assets` export. The strings are
// emitted with `JSON.stringify`, so any backticks / `${` / backslashes in the
// minified output are escaped safely.
//
// Runs last in the package build (after tsup and vite), so `dist/` already
// holds both source files when this executes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');

const js = readFileSync(join(dist, 'contact-widget.js'), 'utf8');
const css = readFileSync(join(dist, 'contact-widget.css'), 'utf8');

const module = `// Generated by scripts/emit-asset-strings.mjs — do not edit.
// The built browser-widget assets, inlined as strings so host adapters can
// bundle and serve them (e.g. @takuhon/cloudflare's /contact-widget.{js,css}).
export const contactWidgetJs = ${JSON.stringify(js)};
export const contactWidgetCss = ${JSON.stringify(css)};
`;

const types = `// Generated by scripts/emit-asset-strings.mjs — do not edit.
/** The built contact-widget IIFE (\`dist/contact-widget.js\`), inlined as a string. */
export declare const contactWidgetJs: string;
/** The built contact-widget stylesheet (\`dist/contact-widget.css\`), inlined as a string. */
export declare const contactWidgetCss: string;
`;

writeFileSync(join(dist, 'assets.js'), module);
writeFileSync(join(dist, 'assets.d.ts'), types);
